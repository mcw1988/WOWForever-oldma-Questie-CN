"""Generate the runtime addon's gap list from the installed QuestieDB artifact.

Reads the baked TOC (base64 -> zlib -> CBOR), finds entity IDs whose zhCN
localization columns are empty, and writes Gaps.lua into the companion AddOn.
No game data is modified.
"""
from qdb_probe import load_meta, load_value

OUT = r"D:\World of Warcraft\_forever_\Interface\AddOns\QuestieCN_Runtime\Gaps.lua"

meta = load_meta()

quest_ids = load_value(meta, "X-Quest-IDS")[0]
zh_quest = load_value(meta, "X-l10n-zhCN-Quest")[0]
quest_name_col, quest_obj_col = zh_quest[0], zh_quest[1]

quest_masks = {}
for i, qid in enumerate(quest_ids):
    mask = 0
    if not quest_name_col[i]:
        mask |= 1
    obj = quest_obj_col[i]
    if not obj or (isinstance(obj, list) and not any(obj)):
        mask |= 2
    if mask:
        quest_masks[int(qid)] = mask

item_ids = load_value(meta, "X-Item-IDS")[0]
zh_item = load_value(meta, "X-l10n-zhCN-Item")[0]
item_gaps = [int(item_ids[i]) for i, v in enumerate(zh_item[0]) if not v]

npc_ids = load_value(meta, "X-Npc-IDS")[0]
zh_npc = load_value(meta, "X-l10n-zhCN-Npc")[0]
npc_gap_count = sum(1 for v in zh_npc[0] if not v)

object_ids = load_value(meta, "X-Object-IDS")[0]
zh_object = load_value(meta, "X-l10n-zhCN-Object")[0]
obj_col = zh_object[0]
object_gap_count = len(object_ids) - (len(obj_col) if isinstance(obj_col, dict) else sum(1 for v in obj_col if v))


def chunks(seq, size=20):
    for i in range(0, len(seq), size):
        yield seq[i:i + size]


lines = []
lines.append("-- Auto-generated by qdb_gen_gaps.py from QuestieDB_Forever.toc. Do not edit.")
lines.append("-- bit 1 = quest name missing, bit 2 = objectivesText missing.")
lines.append("local _, ns = ...")
lines.append("ns.Gaps = {")
lines.append("    quests = {")
items = sorted(quest_masks.items())
for chunk in chunks(items, 12):
    lines.append("        " + ", ".join("[%d]=%d" % (qid, mask) for qid, mask in chunk) + ",")
lines.append("    },")
lines.append("    items = {")
for chunk in chunks(item_gaps, 20):
    lines.append("        " + ", ".join("[%d]=true" % iid for iid in chunk) + ",")
lines.append("    },")
lines.append("    stats = {")
lines.append("        questNames = %d," % sum(1 for m in quest_masks.values() if m & 1))
lines.append("        questObjectives = %d," % sum(1 for m in quest_masks.values() if m & 2))
lines.append("        itemNames = %d," % len(item_gaps))
lines.append("        npcNames = %d," % npc_gap_count)
lines.append("        objectNames = %d," % object_gap_count)
lines.append("        source = \"QuestieDB_Forever.toc zhCN blocks\",")
lines.append("    },")
lines.append("}")
lines.append("")

with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines))

print("wrote", OUT)
print("quest gaps", len(quest_masks), "item gaps", len(item_gaps),
      "npc gaps", npc_gap_count, "object gaps", object_gap_count)
