"""Build an optional static Chinese supplement for quests the client refuses.

Only copies existing Chinese text from wowforever.wclbox.com (a Forever Chinese
database whose quest text comes from the official client / Wowhead Forever data).
Nothing is translated here. Output: Static.lua in the companion addon folder.
"""
import re
import html
import os
import subprocess
import tempfile
import time
import lupa

SAVED = r"D:/World of Warcraft/_forever_/WTF/Account/MACHUANWEI1/SavedVariables/QuestieCN_Runtime.lua"
GAPS = r"D:/World of Warcraft/_forever_/Interface/AddOns/QuestieCN_Runtime/Gaps.lua"
OUT = r"D:/World of Warcraft/_forever_/Interface/AddOns/QuestieCN_Runtime/Static.lua"
BASE = "https://wowforever.wclbox.com/renwu/%d"

lua = lupa.LuaRuntime()
lua.execute(open(SAVED, encoding="utf-8").read())
db = lua.globals().QuestieCN_RuntimeDB
learned = set(int(k) for k in db.quest.keys())

gaps_src = open(GAPS, encoding="utf-8").read()
block = re.search(r"quests = \{(.*?)\n    \},", gaps_src, re.S).group(1)
gaps = {int(a): int(b) for a, b in re.findall(r"\[(\d+)\]=(\d)", block)}

# Forever's own new quests still missing a Chinese name and not learned at runtime.
targets = sorted([q for q, mask in gaps.items()
                  if q >= 90000 and (mask == 1 or mask == 3) and q not in learned],
                 reverse=True)
print("targets:", len(targets), targets)


def strip_tags(raw):
    text = re.sub(r"<[^>]+>", "", raw)
    return html.unescape(text).strip()


def fetch(qid):
    fd, path = tempfile.mkstemp(suffix=".html")
    os.close(fd)
    try:
        result = subprocess.run(
            ["curl", "-sS", "--max-time", "20", "-o", path, "-w", "%{http_code}", BASE % qid],
            capture_output=True, text=True)
        code = (result.stdout or "").strip()
        if code != "200":
            return None
        return open(path, encoding="utf-8", errors="replace").read()
    finally:
        try:
            os.remove(path)
        except OSError:
            pass


def parse(page, qid):
    if not page or "页面不存在" in page[:6000] or "找不到这个页面" in page[:6000]:
        return None
    h1 = re.search(r"<h1[^>]*>(.*?)</h1>", page, re.S)
    name = strip_tags(h1.group(1)) if h1 else ""
    # "任务名任务攻略：" in <title> is a fallback, but h1 is authoritative.
    if not name or "页面不存在" in name or len(name) > 60:
        return None
    if not re.search(r"[\u4e00-\u9fff]", name):
        return None
    objectives = []
    section = re.search(r"<h2[^>]*>任务目标</h2>(.*?)</section>", page, re.S)
    if section:
        for p in re.findall(r"<p[^>]*>(.*?)</p>", section.group(1), re.S):
            text = strip_tags(p)
            if text and re.search(r"[\u4e00-\u9fff]", text) and len(text) < 300:
                objectives.append(text)
    return name, objectives


records = {}
for qid in targets:
    page = fetch(qid)
    parsed = parse(page, qid)
    if parsed:
        records[qid] = parsed
        print("%d -> %s | %s" % (qid, parsed[0], " / ".join(parsed[1])[:90]))
    else:
        print("%d -> no Chinese entry" % qid)
    time.sleep(0.4)

lines = [
    "-- Auto-generated by qdb_fetch_static.py. Not hand-translated.",
    "-- Source: wowforever.wclbox.com/renwu/<id> (Forever Chinese database; quest text",
    "-- comes from the official zhCN client / Wowhead Forever data).",
    "-- Only used for quest ids the client itself refuses to supply.",
    "-- Delete this file (and remove its line from the .toc) to disable this supplement.",
    "local _, ns = ...",
    "ns.Static = {",
    '    source = "wowforever.wclbox.com",',
    "    quests = {",
]
for qid in sorted(records, reverse=True):
    name, objectives = records[qid]
    esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
    obj = ""
    if objectives:
        obj = ', objectives = { %s }' % ", ".join('"%s"' % esc(o) for o in objectives)
    lines.append('        [%d] = { name = "%s"%s },' % (qid, esc(name), obj))
lines += ["    },", "}", ""]

with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines))
print("wrote", OUT, "with", len(records), "quests")
